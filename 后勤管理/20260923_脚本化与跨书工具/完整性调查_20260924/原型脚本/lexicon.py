def title_naming(text):
    """只认《书名》点名（细则里用）：返回 (确定模块, 待定模块)。"""
    ms, pend = set(), set()
    for t in re.findall(r'《\s*([^》]{3,12}?)\s*》', text or ''):
        v = TITLE.get(t)
        if not v:
            continue
        if '|' in v:
            pend.update(v.split('|'))
        else:
            ms.add(v)
    return ms, pend - ms


