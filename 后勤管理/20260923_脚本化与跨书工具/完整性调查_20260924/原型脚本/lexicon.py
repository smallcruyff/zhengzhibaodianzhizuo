def heading_terms(book_index_files, unit_texts):
    """book_index_files: {mod: path}；unit_texts：题面文本列表（算文档频率去泛词）。"""
    tok_mod = collections.defaultdict(set)
    for m, f in book_index_files.items():
        d = json.load(open(f))
        texts = [h.get('text', '') for h in d.get('headings', [])]
        for b in d.get('blocks', []):
            texts += [b.get('node') or '', b.get('method') or '', b.get('h2') or '']
        for x in d.get('drill_items') or []:
            texts.append(x.get('group') or '')
        for t in texts:
            if re.search(r'跨册|跨模块|其他模块|哲学（跨|必修四哲学|形式逻辑与推理', t):
                continue
            t = re.sub(r'^[\s　]*(?:考法\s*\d+|\d+[A-Z]?|[一二三四五六七八九十]+、|\d+\.\d+|A\d|附录\s*[A-Z]?)[\s　、.．]*', '', t)
            t = re.sub(r'[（(]\d+题[）)]', '', t)
            for tok in re.split(r'[\s　、：:，,／/（）()·【】\[\]“”"—–\-；;。!！?？＋+=＝|｜]+', t):
                tok = tok.strip()
                if 2 <= len(tok) <= 10 and re.fullmatch(r'[一-鿿]+', tok) and tok not in STOP:
                    tok_mod[tok].add(m)
    n = max(1, len(unit_texts))
    out = {}
    for tok, ms in tok_mod.items():
        if len(ms) != 1:
            continue
        df = sum(1 for t in unit_texts if tok in t) / n
        if df > 0.06:
            continue
        out[tok] = ms
    return out


def score_text(text, lex, weak=WEAK):
    """返回 {mod: 分}，同一词只计一次；WEAK 词半分。"""
    sc = collections.Counter()
    hits = collections.defaultdict(list)
    for t, ms in lex.items():
        if t in text:
            w = 0.5 if t in weak else 1.0
            for m in ms:
                sc[m] += w / len(ms)
                hits[m].append(t)
    return sc, hits


