def naming(text):
    """设问/细则点名：返回 (确定模块集合, 是否综合, 命中片段, 待定模块集合)。
    《哲学与文化》《逻辑与思维》这类合册书名：按设问里的词再分到哲学/文化、思维/推理；分不出的两边都进待定。"""
    ms = set()
    pend = set()
    frag = []
    t = text or ''
    for m, rx in NAMING:
        for mm in re.finditer(rx, t):
            frag.append(mm.group(0))
            parts = m.split('|')
            if len(parts) == 1:
                ms.add(parts[0])
            else:
                rest = t.replace(mm.group(0), '')
                sup = [x for x in parts if re.search(SPLIT_HINT[x], rest)]
                if len(sup) == 1:
                    ms.add(sup[0])
                    pend.update(x for x in parts if x not in sup)
                else:
                    pend.update(parts)
    pend -= ms
    gen = bool(re.search(GENERIC, t))
    return ms, gen, frag, pend
